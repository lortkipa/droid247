import {
  APP_SCHEME,
  DESKTOP_AUTH_COMPLETE_PATH,
  DESKTOP_AUTH_START_PATH,
  DesktopAuthStateSchema,
} from '@droid247/shared';
import type { Hono } from 'hono';

import { auth } from './auth';

/**
 * Google sign-in for the desktop app. Google doesn't allow its sign-in page in
 * embedded app windows, so the app opens START in the system browser and the
 * whole OAuth round trip (state cookie included) happens there. COMPLETE then
 * hands the new session to the app as a short-lived one-time token through a
 * droid247:// deep link, and the app exchanges it for a bearer token.
 *
 * `state` is generated by the app and echoed back in the deep link; the app
 * ignores links whose state it didn't start, so a crafted link can't sign it
 * in to someone else's account.
 */
export function mountDesktopAuth(app: Hono) {
  app.get(DESKTOP_AUTH_START_PATH, async (c) => {
    const state = DesktopAuthStateSchema.safeParse(c.req.query('state'));
    if (!state.success) {
      return c.text('Invalid sign-in request.', 400);
    }

    const completeURL = `${DESKTOP_AUTH_COMPLETE_PATH}?state=${state.data}`;
    try {
      const { headers, response } = await auth.api.signInSocial({
        body: { provider: 'google', callbackURL: completeURL, errorCallbackURL: completeURL },
        returnHeaders: true,
      });
      if (!response.url) {
        throw new Error('Better Auth returned no authorization URL');
      }
      const redirect = new Response(null, { status: 302, headers: { location: response.url } });
      for (const cookie of headers.getSetCookie()) {
        redirect.headers.append('set-cookie', cookie);
      }
      return redirect;
    } catch (error) {
      console.error('[auth] desktop Google sign-in failed to start:', error);
      return returnToApp(state.data, { error: 'google_unavailable' });
    }
  });

  app.get(DESKTOP_AUTH_COMPLETE_PATH, async (c) => {
    const state = DesktopAuthStateSchema.safeParse(c.req.query('state'));
    if (!state.success) {
      return c.text('Invalid sign-in request.', 400);
    }

    const error = c.req.query('error');
    if (error) {
      return returnToApp(state.data, { error });
    }
    try {
      const { token } = await auth.api.generateOneTimeToken({ headers: c.req.raw.headers });
      return returnToApp(state.data, { token });
    } catch {
      return returnToApp(state.data, { error: 'no_session' });
    }
  });
}

/** A page that opens the desktop app through its deep link. */
function returnToApp(state: string, result: { token: string } | { error: string }) {
  const params = new URLSearchParams({ state, ...result });
  const link = `${APP_SCHEME}://auth?${params.toString()}`;
  const ok = 'token' in result;
  const title = ok ? 'Signed in' : 'Sign-in failed';
  const message = ok
    ? 'Return to the Droid247 app to continue. You can close this tab.'
    : 'Return to the Droid247 app and try again. You can close this tab.';
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Droid247: ${title}</title>
<style>
  :root { color-scheme: light dark; }
  body { margin: 0; min-height: 100vh; display: grid; place-items: center; font: 16px/1.5 system-ui, sans-serif; background: #fff; color: #0B0D12; }
  @media (prefers-color-scheme: dark) { body { background: #000; color: #F4F6FA; } }
  main { max-width: 360px; padding: 24px; text-align: center; }
  h1 { font-size: 24px; margin: 0 0 8px; }
  p { opacity: 0.7; margin: 0; }
</style>
</head>
<body>
<main>
  <h1>${title}</h1>
  <p>${message}</p>
</main>
<script>location.href = ${JSON.stringify(link).replace(/</g, '\\u003c')};</script>
</body>
</html>`;
  return new Response(html, {
    headers: {
      'content-type': 'text/html; charset=utf-8',
      'cache-control': 'no-store',
      'referrer-policy': 'no-referrer',
    },
  });
}
